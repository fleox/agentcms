import i18n from "../../../i18n";
import { toast } from "../../../lib/toast";
import { getRuntimeConfig } from "../../../lib/runtimeConfig";
import { getGitToken } from "../../docstore/gitStore";
import { createRemoteGitTransport, joinRepoPath, type GitChange, type GitTreeEntry } from "../../git";
import type { StorageConnectorFactory } from "../registry";
import { StorageError, type BatchOp, type ListItem, type StorageConnector } from "../types";

// Git-backed publish target: the rendered site is committed to a
// GitHub / GitLab repo and served by whatever watches that repo:
//
//   - "github-pages"     — GitHub Pages ("Deploy from a branch", folder
//                          / or /docs). A `.nojekyll` marker is added so
//                          Pages serves files verbatim (no Jekyll pass,
//                          `_`-prefixed paths kept).
//   - "gitlab-pages"     — GitLab Pages. A minimal `.gitlab-ci.yml` is
//                          added (only if the repo has none) that
//                          publishes `dir` as the Pages artifact.
//   - "cloudflare-pages" — a Cloudflare Pages project connected to the
//                          repo (no build command, output dir = `dir`).
//                          Works with private repos on the free plan.
//   - "other"            — anything else that deploys from a repo
//                          (Netlify, Vercel, a server-side git pull, …).
//
// Model "commit": inside withStorageBatch the whole publish lands as
// ONE commit — one Pages build instead of one per file, which matters
// with build quotas (Cloudflare: 500 builds / month on the free plan,
// GitHub Pages: ~10 builds / hour soft limit).

export type GitPagesHost = "github-pages" | "gitlab-pages" | "cloudflare-pages" | "other";

export interface GitPagesSettings {
  provider: "github" | "gitlab";
  // GitHub
  owner?: string;
  repo?: string;
  // GitLab ("group/repo")
  project?: string;
  branch: string;
  // Empty → reuse the editor's own token when content also lives on the
  // same provider (markdown-git backend), so each editor publishes with
  // their own identity and nothing secret is shared.
  token: string;
  apiBaseUrl?: string;
  // Repo sub-folder holding the site ("" = repo root).
  dir?: string;
  // Public URL the host serves the site at, e.g. https://user.github.io/repo
  siteUrl: string;
  host: GitPagesHost;
}

function gitlabCi(dir: string, branch: string): string {
  const copy =
    dir === "public"
      ? '    - echo "Publishing public/"'
      : `    - rm -rf public && cp -r ${dir} public`;
  return [
    "# Generated by Flexweg CMS — publishes the static site with GitLab Pages.",
    "# Safe to edit: the CMS only creates this file when the repo has none.",
    "pages:",
    "  stage: deploy",
    "  script:",
    copy,
    "  artifacts:",
    "    paths:",
    "      - public",
    "  rules:",
    `    - if: $CI_COMMIT_BRANCH == "${branch}"`,
    "",
  ].join("\n");
}

export function resolveGitPagesToken(settings: GitPagesSettings): string {
  if (settings.token) return settings.token;
  const runtime = getRuntimeConfig();
  if (runtime?.backend === "markdown-git" && runtime.git.provider === settings.provider) {
    return getGitToken(runtime.git) ?? "";
  }
  return "";
}

// GitHub Pages must be switched on once per repository. After the first
// commit the connector tries it through the API (needs the token's
// "Pages: read and write" permission); without that permission it tells
// the user where to click. Checked once per repo per session.
const pagesChecked = new Set<string>();

async function ensureGithubPages(settings: GitPagesSettings, token: string, dir: string): Promise<void> {
  const key = `${settings.owner}/${settings.repo}`;
  if (pagesChecked.has(key)) return;
  pagesChecked.add(key);
  const api = (settings.apiBaseUrl || "https://api.github.com").replace(/\/+$/, "");
  const url = `${api}/repos/${encodeURIComponent(settings.owner ?? "")}/${encodeURIComponent(settings.repo ?? "")}/pages`;
  const headers = { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json" };
  try {
    const current = await fetch(url, { headers, cache: "no-store" });
    if (current.ok) return;
    const created = await fetch(url, {
      method: "POST",
      headers: { ...headers, "Content-Type": "application/json" },
      body: JSON.stringify({ source: { branch: settings.branch, path: dir === "docs" ? "/docs" : "/" } }),
    });
    if (created.ok) {
      toast.success(i18n.t("connectors.pages.enabled"));
      return;
    }
  } catch {
    // Network / CORS — fall through to the manual hint.
  }
  toast.info(
    i18n.t("connectors.pages.enableHint", {
      repo: key,
      branch: settings.branch,
      folder: dir === "docs" ? "/docs" : "/ (root)",
    }),
  );
}

export function createGitPagesConnector(settings: GitPagesSettings): StorageConnector {
  const token = resolveGitPagesToken(settings);
  // GitLab Pages needs the site in a folder (the Pages artifact can't be
  // the repo root), so it defaults to — and never goes below — "public".
  let dir = String(settings.dir ?? "").replace(/^\/+|\/+$/g, "");
  if (settings.host === "gitlab-pages" && !dir) dir = "public";
  const transport = createRemoteGitTransport(
    settings.provider === "github"
      ? {
          provider: "github",
          owner: settings.owner ?? "",
          repo: settings.repo ?? "",
          branch: settings.branch,
          token,
          apiBaseUrl: settings.apiBaseUrl,
        }
      : {
          provider: "gitlab",
          project: settings.project ?? "",
          branch: settings.branch,
          token,
          apiBaseUrl: settings.apiBaseUrl,
        },
  );
  const siteUrl = (settings.siteUrl ?? "").replace(/\/+$/, "");
  const repoPath = (path: string) => joinRepoPath(dir, path);
  const sitePath = (path: string) => (dir ? path.slice(dir.length + 1) : path);
  const inSite = (path: string) => !dir || path.startsWith(dir + "/");

  let cache: { head: string; files: Map<string, GitTreeEntry> } | null = null;

  async function tree() {
    const head = await transport.headSha();
    if (cache && cache.head === head) return cache;
    const listed = await transport.listTree();
    cache = { head: listed.headSha, files: new Map(listed.entries.map((e) => [e.path, e])) };
    return cache;
  }

  // Host-specific marker files, added once.
  function hostExtras(files: Map<string, GitTreeEntry>): GitChange[] {
    if (settings.host === "github-pages") {
      const marker = repoPath(".nojekyll");
      return files.has(marker) ? [] : [{ type: "put", path: marker, content: "" }];
    }
    if (settings.host === "gitlab-pages") {
      return files.has(".gitlab-ci.yml")
        ? []
        : [{ type: "put", path: ".gitlab-ci.yml", content: gitlabCi(dir, settings.branch) }];
    }
    return [];
  }

  async function commitBatch(ops: BatchOp[]): Promise<void> {
    const { files } = await tree();
    const changes: GitChange[] = [];
    let count = 0;
    for (const op of ops) {
      if (op.type === "deletePrefix") {
        const prefix = repoPath(op.path) + "/";
        for (const path of files.keys()) {
          if (path.startsWith(prefix)) changes.push({ type: "delete", path });
        }
      } else if (op.type === "delete") {
        // Already-gone paths are a no-op (and must not inflate the
        // commit message's "removed" count).
        if (files.has(repoPath(op.path))) changes.push({ type: "delete", path: repoPath(op.path) });
      } else {
        changes.push({ type: "put", path: repoPath(op.path), content: op.content, encoding: op.encoding });
        count++;
      }
    }
    changes.push(...hostExtras(files));
    const deleted = changes.filter((c) => c.type === "delete").length;
    const summary = [count && `${count} updated`, deleted && `${deleted} removed`].filter(Boolean).join(", ");
    await transport.commit(changes, { message: `Publish site${summary ? ` (${summary})` : ""} — Flexweg CMS` });
    cache = null;
    if (settings.host === "github-pages" && settings.provider === "github") {
      void ensureGithubPages(settings, token, dir);
    }
  }

  return {
    id: "git-pages",
    model: "commit",
    capabilities: {
      list: true,
      rename: false,
      renameFolder: false,
      folders: false,
      deletePrefix: true,
      storageLimits: false,
    },

    // Outside a batch every write is its own commit — correct, just noisy.
    put: (input) => commitBatch([{ type: "put", ...input }]),
    delete: (path) => commitBatch([{ type: "delete", path }]),
    deletePrefix: (path) => commitBatch([{ type: "deletePrefix", path }]),
    commitBatch,

    async get(path) {
      const { files } = await tree();
      const entry = files.get(repoPath(path));
      if (!entry) throw new StorageError(`File not found: ${path}`, 404);
      const texts = await transport.readTexts([entry]);
      const text = texts.get(entry.path);
      if (text === undefined) throw new StorageError(`File not found: ${path}`, 404);
      return text;
    },

    async getBytes(path) {
      const { files } = await tree();
      const entry = files.get(repoPath(path));
      return entry ? transport.readBytes(entry) : null;
    },

    async list(page, perPage) {
      const { files } = await tree();
      const all: ListItem[] = [...files.values()]
        .filter((e) => inSite(e.path))
        .map((e) => ({ path: sitePath(e.path), type: "file" as const, size: e.size, url: `${siteUrl}/${sitePath(e.path)}` }))
        .sort((a, b) => (a.path < b.path ? -1 : 1));
      return { items: all.slice((page - 1) * perPage, page * perPage), page, per_page: perPage, total: all.length };
    },

    async publicUrl(path) {
      return `${siteUrl}/${path.replace(/^\/+/, "")}`;
    },
  };
}

export const gitPagesFactory: StorageConnectorFactory<GitPagesSettings> = {
  id: "git-pages",
  create: createGitPagesConnector,
};
